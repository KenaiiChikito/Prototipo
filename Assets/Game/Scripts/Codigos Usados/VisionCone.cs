using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Genera el cono de visión tipo Among Us.
/// Pon este script en un hijo del jugador local, a nivel del suelo (Y ? 0.05).
/// Requiere: MeshFilter + MeshRenderer con el material VisionMaskMat.
/// </summary>
[RequireComponent(typeof(MeshFilter), typeof(MeshRenderer))]
public class VisionCone : MonoBehaviour
{
    [Header("Visión")]
    [Tooltip("Radio máximo de visión en unidades de mundo")]
    public float viewRadius = 8f;

    [Tooltip("Rayos por 360°. Más = más suave pero más costoso (90–360 es el rango ideal)")]
    [Range(30, 720)]
    public int rayCount = 180;

    [Tooltip("Iteraciones de búsqueda binaria para bordes nítidos en esquinas de paredes")]
    [Range(1, 8)]
    public int edgeIterations = 4;

    [Tooltip("Diferencia de distancia mínima para activar la detección de borde")]
    public float edgeDistanceThreshold = 0.5f;

    [Header("Layers")]
    [Tooltip("Layer de las paredes/obstáculos que bloquean la visión")]
    public LayerMask wallLayer;

    // ??? Private ?????????????????????????????????????????????????????????????
    private Mesh _viewMesh;
    private readonly List<PlayerVisibilityTarget> _players = new();

    // ??? Unity ???????????????????????????????????????????????????????????????
    void Awake()
    {
        _viewMesh = new Mesh { name = "VisionMesh" };
        GetComponent<MeshFilter>().mesh = _viewMesh;
    }

    void LateUpdate()
    {
        BuildVisionMesh();
        RefreshPlayerVisibility();
    }

    // ??? API pública ??????????????????????????????????????????????????????????
    public void RegisterPlayer(PlayerVisibilityTarget p)
    {
        if (!_players.Contains(p)) _players.Add(p);
    }

    public void UnregisterPlayer(PlayerVisibilityTarget p) => _players.Remove(p);

    // ?????????????????????????????????????????????????????????????????????????
    // GENERACIÓN DEL MESH
    // ?????????????????????????????????????????????????????????????????????????
    void BuildVisionMesh()
    {
        float angleStep = 360f / rayCount;
        var edgePoints = new List<Vector3>(rayCount * 2);

        // Primer raycast (0°) y lo añadimos al inicio
        ViewCastInfo prev = ViewCast(0f);
        edgePoints.Add(ToLocal(prev.point));

        for (int i = 1; i <= rayCount; i++)
        {
            float angle = i * angleStep;
            ViewCastInfo curr = ViewCast(angle);

            // Detectar transición hit?miss o salto de distancia (esquina de pared)
            bool hitTransition = prev.hit != curr.hit;
            bool distJump = prev.hit && curr.hit &&
                                 Mathf.Abs(prev.dist - curr.dist) > edgeDistanceThreshold;

            if (hitTransition || distJump)
            {
                // Búsqueda binaria para encontrar el borde exacto
                EdgeInfo edge = FindEdge(prev, curr);
                edgePoints.Add(ToLocal(edge.A));
                edgePoints.Add(ToLocal(edge.B));
            }

            edgePoints.Add(ToLocal(curr.point));
            prev = curr;
        }

        ApplyMesh(edgePoints);
    }

    void ApplyMesh(List<Vector3> pts)
    {
        int n = pts.Count;
        if (n < 2) return;

        // Vértice 0 = centro, vértices 1..n = borde del cono
        var verts = new Vector3[n + 1];
        var tris = new int[(n - 1) * 3];

        verts[0] = Vector3.zero;
        for (int i = 0; i < n; i++)
            verts[i + 1] = pts[i];

        // Abanico de triángulos desde el centro
        for (int i = 0; i < n - 1; i++)
        {
            tris[i * 3] = 0;
            tris[i * 3 + 1] = i + 1;
            tris[i * 3 + 2] = i + 2;
        }

        _viewMesh.Clear();
        _viewMesh.vertices = verts;
        _viewMesh.triangles = tris;
        _viewMesh.RecalculateNormals();
    }

    // ?????????????????????????????????????????????????????????????????????????
    // RAYCASTING
    // ?????????????????????????????????????????????????????????????????????????
    ViewCastInfo ViewCast(float angle)
    {
        Vector3 dir = AngleToDirection(angle);
        Vector3 origin = transform.position;

        if (Physics.Raycast(origin, dir, out RaycastHit hit, viewRadius, wallLayer))
            return new ViewCastInfo(true, hit.point, hit.distance, angle);

        return new ViewCastInfo(false, origin + dir * viewRadius, viewRadius, angle);
    }

    /// <summary>
    /// Búsqueda binaria entre dos rayos para encontrar el borde exacto de una pared.
    /// Produce sombras nítidas en las esquinas (como Among Us).
    /// </summary>
    EdgeInfo FindEdge(ViewCastInfo a, ViewCastInfo b)
    {
        float minAngle = a.angle;
        float maxAngle = b.angle;
        Vector3 pA = a.point;
        Vector3 pB = b.point;

        for (int i = 0; i < edgeIterations; i++)
        {
            float mid = (minAngle + maxAngle) * 0.5f;
            ViewCastInfo midCast = ViewCast(mid);

            bool sameAsA = midCast.hit == a.hit &&
                           Mathf.Abs(midCast.dist - a.dist) <= edgeDistanceThreshold;

            if (sameAsA) { minAngle = mid; pA = midCast.point; }
            else { maxAngle = mid; pB = midCast.point; }
        }

        return new EdgeInfo(pA, pB);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // VISIBILIDAD DE JUGADORES
    // ?????????????????????????????????????????????????????????????????????????
    void RefreshPlayerVisibility()
    {
        Vector3 origin = transform.position;

        foreach (PlayerVisibilityTarget target in _players)
        {
            if (target == null) continue;

            Vector3 toTarget = target.EyePosition - origin;
            float dist = toTarget.magnitude;

            // Visible si: está dentro del radio Y no hay pared entre ambos
            bool visible = dist <= viewRadius &&
                           !Physics.Raycast(origin, toTarget / dist, dist, wallLayer);

            target.SetVisible(visible);
        }
    }

    // ??? Helpers ??????????????????????????????????????????????????????????????
    Vector3 ToLocal(Vector3 world) => transform.InverseTransformPoint(world);

    static Vector3 AngleToDirection(float degrees)
    {
        float r = degrees * Mathf.Deg2Rad;
        // Rota en el plano XZ (vista top-down)
        return new Vector3(Mathf.Sin(r), 0f, Mathf.Cos(r));
    }

    // ??? Tipos internos ???????????????????????????????????????????????????????
    readonly struct ViewCastInfo
    {
        public readonly bool hit;
        public readonly Vector3 point;
        public readonly float dist;
        public readonly float angle;

        public ViewCastInfo(bool hit, Vector3 point, float dist, float angle)
        {
            this.hit = hit; this.point = point;
            this.dist = dist; this.angle = angle;
        }
    }

    readonly struct EdgeInfo
    {
        public readonly Vector3 A, B;
        public EdgeInfo(Vector3 a, Vector3 b) { A = a; B = b; }
    }
}